"""Build the publication PDFs and manuscript.tex from the Markdown sources (M6).

Route (DEC-003): pandoc 3.6.3 to Typst with mainfont Libertinus Serif, compiled
with the typst Python package of the shared tools interpreter; manuscript.tex is
generated by pandoc and not compiled (no TeX distribution). The leading SPDX
comment is dropped and the first level-1 heading of each source is passed as the
``title`` metadata, so the PDF metadata carries a title and the heading is not
printed twice. The intermediate ``.typ`` files are written to
a scratch directory, never into the repository. The sources embed no images, so the
compile root is that scratch directory.

Usage:
    .venv/bin/python scripts/build_publication_pdfs.py [--typ-dir DIR] [--png-dir DIR]

``--png-dir`` additionally renders every page to PNG (60 ppi) for visual inspection.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TOOLS = Path(os.environ.get("ECHO_TOOLS", REPO.parent / ".tools"))
PANDOC = TOOLS / "pandoc"
PY = TOOLS / "py" / "bin" / "python"

SOURCES = [
    "research/paper/manuscript.md",
    "research/paper/supplementary.md",
    "research/experiments/EXP-001/report.md",
    "research/experiments/EXP-002/report.md",
    "research/experiments/EXP-003/report.md",
    "research/experiments/EXP-004/report.md",
]
PANDOC_ARGS = ["-f", "markdown", "-s", "-V", "mainfont=Libertinus Serif"]
# Long tables break across pages and use 0.85em text (wide tables would otherwise collide); inline code inside a table may wrap after "/" and every 12 characters
# (paths would otherwise overflow the cell); a 64-hex SHA-256 in a table may wrap every 16 characters.
TYPST_HEADER = (
    "#show figure.where(kind: table): set block(breakable: true)\n"
    "#show table: set text(size: 0.85em)\n"
    "#show table: it => { show raw.where(block: false): r => text(font: \"DejaVu Sans Mono\", size: 0.8em, "
    'r.text.replace(regex("/|[^/]{12}"), m => m.text + sym.zws)); '
    'show regex("[0-9a-f]{64}"): h => h.text.clusters().chunks(16).map(c => c.join()).join(sym.zws); it }'
)
TYPST_ARGS = ["-V", f"header-includes={TYPST_HEADER}"]

COMPILE = """
import sys, typst
typ, pdf, root, png = sys.argv[1:5]
typst.compile(typ, output=pdf, root=root)
if png:
    typst.compile(typ, output=png, format="png", ppi=60, root=root)
"""


def tag(rel: str) -> str:
    p = Path(rel)
    return p.stem if p.parent.name == "paper" else f"{p.parent.name}-report"


def split_title(text: str) -> tuple[str, str]:
    """Return (title, body): drop leading HTML comment lines, take the first '# ' heading."""
    lines = text.splitlines()
    while lines and (lines[0].startswith("<!--") or not lines[0].strip()):
        lines.pop(0)
    if not lines or not lines[0].startswith("# "):
        raise ValueError("source does not start with a level-1 heading")
    return lines[0][2:].strip(), "\n".join(lines[1:]) + "\n"


def pandoc(src: Path, args: list[str]) -> None:
    title, body = split_title(src.read_text(encoding="utf-8"))
    subprocess.run([str(PANDOC), *args, "-M", f"title={title}"], input=body, text=True, cwd=src.parent, check=True)


def build(rel: str, typ_dir: Path, png_dir: Path | None) -> Path:
    src = REPO / rel
    typ = typ_dir / f"{tag(rel)}.typ"
    pandoc(src, [*PANDOC_ARGS, *TYPST_ARGS, "-t", "typst", "-o", str(typ)])
    pdf = src.with_suffix(".pdf")
    png = str(png_dir / f"{tag(rel)}-{{p}}.png") if png_dir else ""
    subprocess.run([str(PY), "-I", "-c", COMPILE, str(typ), str(pdf), str(typ_dir), png], check=True)
    return pdf


def build_tex() -> Path:
    src = REPO / "research/paper/manuscript.md"
    tex = src.with_suffix(".tex")
    pandoc(src, [*PANDOC_ARGS[:-2], "-t", "latex", "-o", tex.name])
    tex.write_text("% SPDX-License-Identifier: LicenseRef-ECHO-NC-Research-1.0\n" + tex.read_text(encoding="utf-8"), encoding="utf-8")
    return tex


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--typ-dir", default=None)
    ap.add_argument("--png-dir", default=None)
    a = ap.parse_args(argv)
    if not PANDOC.exists() or not PY.exists():
        print(f"SKIPPED: pandoc or the typst interpreter not found under {TOOLS}", file=sys.stderr)
        return 2
    typ_dir = Path(a.typ_dir) if a.typ_dir else Path(tempfile.mkdtemp(prefix="echo-typ-"))
    typ_dir.mkdir(parents=True, exist_ok=True)
    png_dir = Path(a.png_dir) if a.png_dir else None
    if png_dir:
        png_dir.mkdir(parents=True, exist_ok=True)
    for rel in SOURCES:
        pdf = build(rel, typ_dir, png_dir)
        print(f"OK {pdf.relative_to(REPO)} {pdf.stat().st_size} bytes")
    print(f"OK {build_tex().relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
